-- Bolsas de efectivo — la bolsa nace sola, y el circuito llega hasta el conteo.
--
-- Dos pedidos del usuario (2026-08-15):
--
--   1. «al confirmar el corte, se debe guardar la bolsa automaticamente».
--      La version anterior lo hacia en dos pasos a proposito —meter el dinero
--      es un acto fisico— y el usuario decidio lo contrario. Queda anotado el
--      efecto: el registro afirma que la bolsa existe apenas se firma el corte,
--      asi que la correccion pasa a ser `anular_bolsa`, que exige motivo y
--      queda en la bitacora. A cambio, el invariante se cumple solo: todo corte
--      confirmado tiene su bolsa.
--
--   2. La vista donde vive el proceso entero, incluido el conteo en
--      administracion: ENTREGADA -> RECIBIDA -> CONTADA, y la resolucion de la
--      diferencia.
--
-- Probada en el branch de staging con una transaccion revertida: sin bolsa
-- mientras el corte esta PENDIENTE, S3-1001 por 666.65 al confirmar el primero,
-- S3-1002 por 511.25 al confirmar el segundo (suma 1177.90 = lo declarado en el
-- ultimo corte, que es el invariante), y reconfirmar no duplica.

SET lock_timeout = '5s';

ALTER TABLE public.bolsas
    ADD COLUMN IF NOT EXISTS entregada_por uuid REFERENCES public.employees(id),
    ADD COLUMN IF NOT EXISTS entregada_at  timestamptz,
    ADD COLUMN IF NOT EXISTS recibida_por  uuid REFERENCES public.employees(id),
    ADD COLUMN IF NOT EXISTS recibida_at   timestamptz,
    -- Lo que conto administracion. NO se edita nunca: si al reponer se
    -- sobreescribiera, el faltante desapareceria de la historia y con el la
    -- razon por la que alguien puso dinero de su bolsillo.
    ADD COLUMN IF NOT EXISTS contado       numeric(12,2),
    ADD COLUMN IF NOT EXISTS contado_por   uuid REFERENCES public.employees(id),
    ADD COLUMN IF NOT EXISTS contado_at    timestamptz,
    ADD COLUMN IF NOT EXISTS dif_via       text,
    ADD COLUMN IF NOT EXISTS dif_causa     text,
    ADD COLUMN IF NOT EXISTS dif_por       uuid REFERENCES public.employees(id),
    ADD COLUMN IF NOT EXISTS dif_at        timestamptz;

DO $$ BEGIN
    ALTER TABLE public.bolsas ADD CONSTRAINT bolsas_dif_via_valida
        CHECK (dif_via IS NULL OR dif_via IN ('REPONE','RETIRA','JUSTIFICA'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

