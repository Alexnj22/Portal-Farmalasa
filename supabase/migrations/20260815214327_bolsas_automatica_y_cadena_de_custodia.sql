-- ── A quien se le avisa ─────────────────────────────────────────────────────
-- `destinatarios_de_cortes` era esta misma consulta con el modulo escrito
-- adentro. Se generaliza en vez de copiarla: dos versiones de «a quien de esta
-- sala le importa» se desincronizan, y desincronizadas significan que a alguien
-- deja de llegarle un aviso de dinero.
CREATE OR REPLACE FUNCTION public.destinatarios_de_modulo(p_branch_id integer, p_module_key text)
RETURNS uuid[]
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, extensions
AS $$
    -- Los de la sala que tienen el modulo. `notify_branch` avisaria a TODOS los
    -- de la sucursal, y a quien no lo tiene el aviso lo manda a una pantalla que
    -- no puede abrir.
    SELECT array_agg(DISTINCT e.id)
      FROM public.employees e
      JOIN public.role_permissions rp
        ON rp.role_id = e.role_id
       AND rp.module_key = p_module_key
     WHERE e.branch_id = p_branch_id
       AND e.status = 'ACTIVO'
       AND (rp.can_view OR rp.can_edit);
$$;

REVOKE EXECUTE ON FUNCTION public.destinatarios_de_modulo(integer, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.destinatarios_de_modulo(integer, text) TO authenticated, service_role;

