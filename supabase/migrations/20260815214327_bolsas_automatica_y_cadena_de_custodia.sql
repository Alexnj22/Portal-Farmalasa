-- ── Permisos ────────────────────────────────────────────────────────────────
-- `bolsas_conteo` es un modulo APARTE de `bolsas` porque son dos publicos: la
-- sala entrega, administracion recibe y cuenta. Con un solo permiso, darle a la
-- sala lo suyo le daria tambien el poder de dar por buena su propia bolsa.
--
-- Se siembra a los cargos que hoy ven TODAS las salas en cortes de caja: son
-- los de administracion. Los de sala (scope BRANCH) quedan fuera a proposito.
INSERT INTO public.role_permissions (role_id, module_key, can_view, can_edit, can_approve, scope)
SELECT rp.role_id, 'bolsas_conteo', true, rp.can_edit, false, 'ALL'
  FROM public.role_permissions rp
 WHERE rp.module_key = 'cortes_caja' AND rp.scope = 'ALL'
ON CONFLICT (role_id, module_key) DO NOTHING;
