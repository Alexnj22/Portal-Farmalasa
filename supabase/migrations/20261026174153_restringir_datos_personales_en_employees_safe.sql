-- Restringe los datos personales/HR de employees_safe a quien tenga permiso de
-- Personal (staff_list/staff_detail/datos_personales con can_view) o esté
-- mirando su PROPIA ficha. El directorio (nombre, foto, sala, cargo, estado) y
-- lo operativo del horario (weekly_schedule, exceptions, shift_id, hours_owed)
-- siguen visibles para todos. Hallazgo de la auditoría de seguridad 2026-10-26:
-- cualquier empleado autenticado podía leer domicilio, teléfono, fecha de
-- nacimiento, contactos de emergencia, discapacidad y condiciones crónicas de
-- todo el personal. Mismo nombre, columnas, orden y tipos que la vista previa
-- (CREATE OR REPLACE no admite cambiarlos), así que el frontend no cambia.
SET lock_timeout = '5s';

CREATE OR REPLACE VIEW public.employees_safe
WITH (security_invoker=true) AS
WITH ctx AS (
  SELECT
    ( public.auth_has_module_permission('staff_list','can_view')
      OR public.auth_has_module_permission('staff_detail','can_view')
      OR public.auth_has_module_permission('datos_personales','can_view') ) AS ver_personal,
    public.auth_employee_id() AS mi_id
)
SELECT
    e.id,
    e.branch_id,
    e.shift_id,
    e.photo_url,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.phone END)::text AS phone,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.address END)::text AS address,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.birth_date END)::date AS birth_date,
    e.status,
    e.hire_date,
    e.weekly_schedule,
    e.exceptions,
    e.created_at,
    e.role_id,
    e.secondary_role_id,
    e.username,
    e.first_names,
    e.last_names,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.gender END)::text AS gender,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.blood_type END)::text AS blood_type,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.marital_status END)::text AS marital_status,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.emergency_contact_name END)::text AS emergency_contact_name,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.emergency_contact_phone END)::text AS emergency_contact_phone,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contract_type END)::text AS contract_type,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.weekly_contracted_hours END)::integer AS weekly_contracted_hours,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.department END)::text AS department,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.municipality END)::text AS municipality,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.education_level END)::text AS education_level,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.profession END)::text AS profession,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contract_end_date END)::date AS contract_end_date,
    e.name,
    CASE WHEN rango_de_empleado(e.id) >= 4 THEN 'ADMIN'::text WHEN rango_de_empleado(e.id) = 3 THEN 'SUPERVISOR'::text WHEN rango_de_empleado(e.id) >= 1 THEN 'JEFE'::text ELSE 'EMPLEADO'::text END AS system_role,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.email END)::text AS email,
    e.hours_owed,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.afp_institution END)::text AS afp_institution,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.account_type END)::text AS account_type,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.education_grade_completed END)::text AS education_grade_completed,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.education_specialty END)::text AS education_specialty,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.is_studying END)::boolean AS is_studying,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.study_start_date END)::date AS study_start_date,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.study_duration_years END)::numeric(3,1) AS study_duration_years,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.extra_phones END)::text[] AS extra_phones,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.extra_addresses END)::jsonb AS extra_addresses,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.additional_skills END)::jsonb AS additional_skills,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.has_maestria END)::boolean AS has_maestria,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.maestria_title END)::text AS maestria_title,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.maestria_is_studying END)::boolean AS maestria_is_studying,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.maestria_study_start_date END)::date AS maestria_study_start_date,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.maestria_study_duration_years END)::numeric AS maestria_study_duration_years,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.economic_dependents END)::jsonb AS economic_dependents,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.emergency_contact_relationship END)::text AS emergency_contact_relationship,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.emergency_contact_extra_phones END)::text[] AS emergency_contact_extra_phones,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contract_start_date END)::date AS contract_start_date,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.has_motorcycle END)::boolean AS has_motorcycle,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.has_car END)::boolean AS has_car,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.has_motorcycle_license END)::boolean AS has_motorcycle_license,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.has_car_license END)::boolean AS has_car_license,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.has_srs_accreditation END)::boolean AS has_srs_accreditation,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.srs_accreditation_expiry END)::date AS srs_accreditation_expiry,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.nationality END)::text AS nationality,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contract_temporal_legal_basis END)::text AS contract_temporal_legal_basis,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contract_temporal_reason END)::text AS contract_temporal_reason,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.employee_documents END)::jsonb AS employee_documents,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.alt_identity_document_type END)::text AS alt_identity_document_type,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.nursing_license_number END)::text AS nursing_license_number,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.pharmacist_license_number END)::text AS pharmacist_license_number,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.has_disability END)::boolean AS has_disability,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.disability_type END)::text AS disability_type,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.disability_grade END)::text AS disability_grade,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.disability_has_certification END)::boolean AS disability_has_certification,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.chronic_conditions END)::jsonb AS chronic_conditions,
    e.blocked_until,
    e.blocked_reason,
    e.blocked_at,
    e.blocked_by,
    e.suplente_id,
    e.carne_pendiente,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.periodo_pago END)::text AS periodo_pago,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.herramientas_entregadas END)::jsonb AS herramientas_entregadas,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contrato_lugar_celebracion END)::text AS contrato_lugar_celebracion,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contrato_fecha_celebracion END)::date AS contrato_fecha_celebracion,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.lugar_nacimiento END)::text AS lugar_nacimiento,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.distrito END)::text AS distrito,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.emergency_contacts END)::jsonb AS emergency_contacts,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.isss_estado END)::text AS isss_estado,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.afp_estado END)::text AS afp_estado,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.medico_license_number END)::text AS medico_license_number,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contador_license_number END)::text AS contador_license_number,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.tiene_acreditacion_dependiente END)::boolean AS tiene_acreditacion_dependiente,
    e.tipo_ficha,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.forma_estipulacion_salario END)::text AS forma_estipulacion_salario,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.medio_pago END)::text AS medio_pago,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.lugar_pago END)::text AS lugar_pago,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.mtps_remitido_fecha END)::date AS mtps_remitido_fecha,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.contrato_prorrogas END)::jsonb AS contrato_prorrogas,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.extra_emails END)::text[] AS extra_emails,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.acreditaciones END)::jsonb AS acreditaciones,
    (CASE WHEN c.ver_personal OR e.id = c.mi_id THEN e.carne_dependiente_url END)::text AS carne_dependiente_url,
    rango_de_empleado(e.id) AS rango
  FROM employees e CROSS JOIN ctx c;